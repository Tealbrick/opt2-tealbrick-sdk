/** The REAL target app of B31 / B32 (generated): a plain write that records the call context, and a destructive op the default apps policy holds. */
export const CAP_TARGET = { product: "tbconf-holdtarget", note: "real_note", del: "real_delete" } as const;
/** The REAL caller app of B32.sdk_local_refusal (generated). */
export const CAP_CALLER = { product: "tbconf-caller" } as const;
/**
 * The fake apps of the groups, by role → product id. `evolution` is the verified product of the spec fixture (BRIDGE §8.5): `a` and `b`
 * are TWO INSTANCES of it with the same grant shape; `my-app` / `tbconf-noprd` carry the other caller products of caller-context.cases.json
 * (a hyphen product; a grant without `prd`); `e` / `d` call the old fake target `t` with / without `tb.hold_status` in their grant.
 */
export const CAP_APPS = { a: "evolution", b: "evolution", g: "my-app", f: "tbconf-noprd", e: "tbconf-statuscaller", d: "tbconf-nostatus", t: "tbconf-oldtarget" } as const;
export type CapRole = keyof typeof CAP_APPS;

const edge = (product: string, operations: string[], crud: Operation["crud"]): Manifest["companions"] => [{ product, operations, crud, purpose: "Generated companion edge for the hold status and caller context rows" }];

/** The fake apps of the groups, derived from `base`; null when one does not validate. `t` lists the read op every derived app has. */
export function capAppManifests(base: Manifest): Record<CapRole, Manifest> | null {
  const out = {} as Record<CapRole, Manifest>;
  const make = (role: CapRole, companions: Manifest["companions"]): boolean => {
    const m = eventManifest(base, CAP_APPS[role], false);
    if (!m) return false;
    const withEdges = { ...m, ...(companions ? { companions } : {}) } as Manifest;
    const v = validateManifest(withEdges);
    if (!v.ok) return false;
    out[role] = v.manifest;
    return true;
  };
  const toTarget = (...ops: string[]) => edge(CAP_TARGET.product, ops, ["read", "create", "delete"]);
  const ok = [
    make("a", toTarget(CAP_TARGET.note, CAP_TARGET.del, "tb.hold_status")),
    make("b", toTarget(CAP_TARGET.note, CAP_TARGET.del, "tb.hold_status")),
    make("g", toTarget(CAP_TARGET.note)),
    make("f", toTarget(CAP_TARGET.note)),
    make("e", edge(CAP_APPS.t, [EVENT_READ_OP, "tb.hold_status"], ["read"])),
    make("d", edge(CAP_APPS.t, [EVENT_READ_OP], ["read"])),
    make("t", undefined),
  ];
  return ok.every(Boolean) ? out : null;
}

const op = (id: string, crud: Operation["crud"], effect: Operation["effect"], holdFamily?: Operation["holdFamily"]): Operation => ({
  id,
  title: `Generated ${id}`,
  description: "Generated conformance operation with a receipt.",
  input: { type: "object", properties: { id: { type: "string" } } },
  output: { type: "object" },
  crud,
  effect,
  ...(holdFamily ? { holdFamily } : {}),
  idempotency: "required",
  receipt: true,
  audience: "agent",
});

/** Manifest of the real target: `base` (an example manifest) reduced to the two generated ops, listening on `port`. */
export function capTargetManifest(base: Manifest, port: number): Manifest {
  const b = structuredClone(base) as Manifest & Record<string, unknown>;
  const m: Record<string, unknown> = {
    ...(b.$schema !== undefined ? { $schema: b.$schema } : {}),
    schema: b.schema,
    id: CAP_TARGET.product,
    name: "Conformance hold target",
    summary: "Generated SDK app for the hold status and caller context rows.",
    description: "Generated by the conformance suite: a real SDK app with a plain write and a destructive operation that the apps policy holds.",
    version: "1.0.0",
    sdkMajor: b.sdkMajor,
    publisher: b.publisher,
    source: b.source,
    icon: b.icon,
    discovery: b.discovery,
    backups: b.backups,
    runtime: { build: b.runtime.build, port, healthPath: b.runtime.healthPath, resources: b.runtime.resources, volumes: b.runtime.volumes },
    operations: [op(CAP_TARGET.note, ["create"], "write"), op(CAP_TARGET.del, ["delete"], "destructive", "destructive")],
    ...(b.ui ? { ui: b.ui } : {}),
  };
  const v = validateManifest(m);
  if (!v.ok) throw new Error(`hold target manifest invalid: ${v.errors.slice(0, 4).map((e) => `${e.path} ${e.code} ${e.message}`).join("; ")}`);
  return v.manifest;
}

/** What the target's handlers saw: runs of each op and the last op context. */
export interface TargetRuns {
  note: number;
  del: number;
  lastContext: Json | null;
}
export interface CapTarget extends RealRunningApp {
  runs: TargetRuns;
  /** SQLite file of the app (white-box: B31.hold_denied_repeat_blocked ages a hold the way the SDK's own sweep would) */
  dataDir: string;
}

/** defineApp + startApp for the target: `real_note` records ctx.context and echoes it, `real_delete` counts its runs. */
export async function startCapTarget(sdk: SdkModule, manifest: Manifest, env: Record<string, string>, dataDir: string, portalRootKeys: unknown[]): Promise<CapTarget> {
  const migrations = join(dataDir, "migrations");
  mkdirSync(migrations, { recursive: true });
  writeFileSync(join(migrations, "0001_init.sql"), "CREATE TABLE conformance_cap (id TEXT PRIMARY KEY);\n");
  const runs: TargetRuns = { note: 0, del: 0, lastContext: null };
  const app = sdk.defineApp({
    manifest,
    handlers: {
      [CAP_TARGET.note]: async (_input: unknown, ctx: { context?: Json }) => {
        runs.note += 1;
        runs.lastContext = (ctx.context ?? {}) as Json;
        return { written: true, context: (ctx.context ?? {}) as Json };
      },
      [CAP_TARGET.del]: async () => {
        runs.del += 1;
        return { deleted: true };
      },
    },
    migrations,
  });
  const privilegeProc = { getuid: () => 1000 };
  const running = await sdk.startApp(app, env, { portalRootKeys, privilegeProc });
  return { status: () => running.status(), receipts: running.receipts, stop: () => running.stop(), runs, dataDir };
}

/** One request the proxy saw on the way to the target. */
export interface ProxyHit {
  method: string;
  path: string;
  /** body as the bridge sent it (before any tamper) */
  body: string;
  /** body as forwarded */
  forwarded: string;
}

/**
 * Reverse proxy in front of the real target: the bridge's config names the proxy origin (on TB_OWN_INFRA_ORIGINS), the proxy forwards
 * to the app. It counts what the bridge forwards ("the target is not called") and can rewrite an op body after the bridge signed its
 * proof ("the context changed after signing").
 */
export class TargetProxy {
  readonly hits: ProxyHit[] = [];
  /** rewrites the body of a request to a path (null = forward as is) */
  tamper: ((path: string, body: string) => string) | null = null;
  readonly #server: Server;
  private constructor(server: Server) {
    this.#server = server;
  }

  static async start(port: number, upstreamPort: number): Promise<TargetProxy> {
    let self: TargetProxy | null = null;
    const server = createServer(async (req, res) => {
      try {
        const raw = req.method === "GET" || req.method === "HEAD" ? Buffer.alloc(0) : await readRaw(req, 8 * 1024 * 1024);
        const path = req.url ?? "/";
        const body = raw.toString("utf8");
        const forwarded = self?.tamper ? self.tamper(path, body) : body;
        self?.hits.push({ method: req.method ?? "GET", path, body, forwarded });
        const headers: Record<string, string> = {};
        for (const [k, v] of Object.entries(req.headers)) if (v !== undefined && !["host", "content-length", "connection", "transfer-encoding"].includes(k)) headers[k] = Array.isArray(v) ? v.join(", ") : v;
        const up = await fetch(`http://127.0.0.1:${upstreamPort}${path}`, { method: req.method ?? "GET", headers, ...(raw.length || (req.method !== "GET" && req.method !== "HEAD") ? { body: forwarded } : {}) });
        const text = await up.text();
        res.writeHead(up.status, { "content-type": up.headers.get("content-type") ?? "application/json" });
        res.end(text);
      } catch (e) {
        res.writeHead(502, { "content-type": "application/json" });
        res.end(JSON.stringify({ error: { code: "proxy_error", message: e instanceof Error ? e.message : String(e) } }));
      }
    });
    await listen(server, port);
    self = new TargetProxy(server);
    return self;
  }

  /** hits on the op route (`/tb/v1/ops/<op>`) after the first `from` hits, optionally one op */
  opHits(from = 0, name?: string): ProxyHit[] {
    return this.hits.slice(from).filter((h) => h.path.startsWith("/tb/v1/ops/") && (name === undefined || h.path === `/tb/v1/ops/${name}`));
  }

  stop(): Promise<void> {
    return closeServer(this.#server);
  }
}

/** The owner session of the target app (SDK-API §5): launch with a Portal-signed ticket, then person ops with the session cookie and CSRF token. */
export class OwnerSession {
  readonly #base: string;
  readonly #origin: string;
  #cookie = "";
  #csrf = "";
  constructor(origin: string, product: string) {
    this.#origin = origin;
    this.#base = `${origin}/a/${product}`;
  }

  async signIn(ticket: string): Promise<string | null> {
    const l = await request(`${this.#base}/tb/launch`, { method: "POST", headers: { "content-type": "application/x-www-form-urlencoded", origin: this.#origin }, body: new URLSearchParams({ ticket }).toString() });
    const m = /(?:^|\n)tb_session=([^;\n]+)/.exec(l.headers.getSetCookie().join("\n"));
    if (!m) return `launch answered ${l.status} without a session cookie`;
    this.#cookie = m[1] as string;
    const s = await request(`${this.#base}/tb/v1/session`, { headers: { cookie: `tb_session=${this.#cookie}` } });
    const csrf = (s.body as { csrf?: unknown } | null)?.csrf;
    if (s.status !== 200 || typeof csrf !== "string") return `session answered ${s.status} without a csrf token`;
    this.#csrf = csrf;
    return null;
  }

  op(id: string, input: Json): Promise<HttpAnswer> {
    return request(`${this.#base}/tb/v1/ops/${encodeURIComponent(id)}`, {
      method: "POST",
      headers: { "content-type": "application/json", cookie: `tb_session=${this.#cookie}`, "tb-csrf": this.#csrf, origin: this.#origin },
      body: JSON.stringify({ input }),
    });
  }
}
