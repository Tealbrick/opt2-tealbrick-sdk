// Fixtures of the bridge target groups B31 (app hold status, cap `app_hold_status`) and B32 (caller context, cap `app_call_context`)
// (conformance 0.1.31, spec 0.1.77, BRIDGE §8.3 / §8.5, SDK-API §4.7 / §18.6): the fake caller apps and the old fake target the
// world creates, the manifest of the REAL SDK target app (two ops: a plain write and a destructive one that holds), the target
// proxy (counts what the bridge forwards, can tamper with it) and a small person-session client for the target's owner routes.
// No product id of the example manifests appears here: the apps are generated from `base` like the event apps.

