/** One tool definition as emitted into `TOOLS` (C338). */
export interface KitToolDefGen {
  name: string;
  title: string;
  description: string;
  inputSchema: unknown;
  effect: string;
  listing?: "workflow";
  /** the lazy pair's call tool carries the widest annotations over EVERY static agent op it reaches, lazy and listed (BRIDGE §7.5) */
  annotations?: { readOnlyHint: boolean; destructiveHint: boolean; openWorldHint: boolean };
}

/**
 * QA-SDK48-5: the spec 0.1.73 BRIDGE §7.5 lazy pair, exactly as the bridge lists it for a product with lazy ops: names
 * `<product>__tb_more_search` / `<product>__tb_more_call`, the bridge's texts, and on the call tool the widest effect and
 * annotations over `reachOps` = every static agent op tb_more_call can reach with a full grant (lazy AND listed, workflow
 * ops too: TOOLS is the full-grant list). QA-SDK47D-1: lazy ops alone gave readOnlyHint true next to a listed destructive op.
 * The search tool's text names lazy ops only. Empty when no op is lazy.
 */
export function lazyPairDefs(productId: string, name: string, lazyOps: readonly { id: string; effect: string }[], reachOps: readonly { effect: string }[]): KitToolDefGen[] {
  if (lazyOps.length === 0) return [];
  const more = { search: "tb_more_search", call: "tb_more_call", hintIds: 5 };
  const ids = lazyOps.slice(0, more.hintIds).map((o) => o.id).join(", ");
  const effects = [...lazyOps, ...reachOps].map((o) => o.effect);
  const rank = ["read", "write", "outward", "destructive", "money"];
  const widestEffect = effects.reduce((a, b) => (rank.indexOf(b) > rank.indexOf(a) ? b : a), "read");
  const sep = TOOL_NAME_RULE.separator;
  return [
    { name: `${productId}${sep}${more.search}`, title: `${name}: more tools`, description: `Find more ${name} tools: ${lazyOps.length} not listed here (e.g. ${ids}${lazyOps.length > more.hintIds ? ", …" : ""}). Input: words to look for, or "*" for all. Returns each tool's name, description and input schema; call one with ${productId}${sep}${more.call}.`, inputSchema: DYNAMIC_SEARCH_INPUT_SCHEMA, effect: "read" },
    {
      name: `${productId}${sep}${more.call}`,
      title: `${name}: call a tool`,
      description: `Call one ${name} tool found with ${productId}${sep}${more.search}. Input: {"tool": "<name from the search>", "arguments": {…}}. Same checks, approvals and receipts as a direct call.`,
      inputSchema: DYNAMIC_CALL_INPUT_SCHEMA,
      effect: widestEffect,
      annotations: { readOnlyHint: effects.every((e) => e === "read"), destructiveHint: effects.includes("destructive"), openWorldHint: effects.some((e) => e === "outward" || e === "money") },
    },
  ];
}

/** One client method of the kit. */
interface Method {
  name: string;
  tool: string | null;
  doc: string[];
  signature: string;
  body: string;
}

/** Kit package files under `<product>-kit/`. */
export function genKit(lm: LoadedManifest, opts: { packageName?: string } = {}): GenFiles {
  const { manifest: m } = lm;
  if (opts.packageName !== undefined && (opts.packageName.length > 214 || !/^@[a-z0-9][a-z0-9-]*\/[a-z0-9][a-z0-9-]*$/u.test(opts.packageName))) {
    throw new GenError("package_name_invalid", `--package-name must be a scoped npm name (@scope/name, at most 214 characters), got ${JSON.stringify(opts.packageName.slice(0, 80))}`);
  }
  const dir = kitDirName(m.id);
  const files: GenFiles = new Map();
  files.set(`${dir}/package.json`, kitPackageJson(m, opts.packageName));
  files.set(`${dir}/tsconfig.json`, stableJson(KIT_TSCONFIG));
  files.set(`${dir}/src/index.ts`, kitIndex(lm));
  files.set(`${dir}/README.md`, kitReadme(m, opts.packageName));
  return files;
}

