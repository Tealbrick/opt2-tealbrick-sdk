function kitPackageJson(m: Manifest, packageName?: string): string {
  return stableJson({
    name: packageName ?? kitPackageName(m.id),
    version: m.version,
    private: true,
    description: `Typed kit for ${m.name}: operation ids, input/output types, MCP tool names, skills and a client over the bridge MCP tools.`,
    license: m.source.license,
    type: "module",
    exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.js" } },
    files: ["dist", "src", "README.md"],
    scripts: { build: "tsc -p tsconfig.json" },
  });
}

function opDoc(op: OperationView, unlockedBy: Map<string, string>): string[] {
  const lines = [op.title];
  if (!op.standard && op.description) lines.push(op.description.replace(/\s+/g, " "));
  const facts = [`crud ${op.crud.join(",")}`, `effect ${op.effect}`, `idempotency ${op.idempotency}`];
  if (!op.standard && op.holdFamily) facts.push(`hold family ${op.holdFamily}`);
  if (!op.standard && op.scopeType) facts.push(`scope ${op.scopeType}`);
  lines.push(facts.join(" · "));
  const req = unlockedBy.get(op.id);
  if (req) lines.push(`Listed only when product \`${req}\` is deployed in the same workspace (unlock).`);
  return lines.map((l) => l.replaceAll("*/", "*\\/"));
}

function kitIndex(lm: LoadedManifest): string {
  const { manifest: m, digest } = lm;
  const em = new SchemaEmitter();
  const ops = withStandardOps(m);
  const unlockedBy = new Map<string, string>();
  for (const u of m.unlocks ?? []) for (const id of u.provides.operations ?? []) unlockedBy.set(id, u.requires);

  // Reserved names of the fixed runtime section.
  for (const n of ["KitMcp", "KitToolResult", "KitHeld", "KitCall", "KitCallOptions", "KitIdempotent", "KitError", "KitClient", "KitSkill", "KitCatalogEntry", "KitSearchInput", "KitDynamicCallInput", "TbHoldStatusInput", "TbHoldStatusOutput", "OpId", "ToolName", "PersonOpId", "PersonOps"])
    em.reserve(n);

  const types: string[] = [];
  const opKeys = new Map<string, string>();
  for (const op of m.operations) {
    const key = camel(op.id);
    if ([...opKeys.values()].includes(key)) throw new GenError("name_collision", `operation ${op.id} maps to an existing name ${key}`);
    opKeys.set(op.id, key);
    for (const [part, schema] of [
      ["Input", op.input],
      ["Output", op.output],
    ] as const) {
      if (!schema) continue;
      const name = `${pascal(op.id)}${part}`;
      em.reserve(name);
      const doc = docOf(schema);
      types.push(`/** ${doc ?? `${part} of \`${op.id}\` (${op.title.replaceAll("*/", "*\\/")}).`} */\nexport type ${name} = ${em.emit(schema, schema, name)};`);
    }
  }
  types.push(`/** Input of \`${mcpToolName(m.id, "tb.hold_status")}\`. */\nexport type TbHoldStatusInput = ${em.emit(standardOpInputSchema("tb.hold_status"), null, "TbHoldStatusInput")};`);
  types.push(`/** Input of a search-mode \`<product>__<op>_search\` tool. */\nexport type KitSearchInput = ${em.emit(DYNAMIC_SEARCH_INPUT_SCHEMA, null, "KitSearchInput")};`);
  types.push(`/** Input of a search-mode \`<product>__<op>_call\` tool. */\nexport type KitDynamicCallInput = ${em.emit(DYNAMIC_CALL_INPUT_SCHEMA, null, "KitDynamicCallInput")};`);

  const tools: [string, string][] = [];
  const methods: Method[] = [];
  // C338 (agent packages): the tool definitions the bridge lists for an agent with a full grant, so a harness can
  // register them without an MCP round trip. Dynamic list-mode entries are per agent and are not listed here.
  const toolDefs: KitToolDefGen[] = [];
  const lazyOps: { id: string; effect: string }[] = [];
  /** every static agent op (lazy and listed): what tb_more_call reaches with a full grant */
  const staticOps: { id: string; effect: string }[] = [];
  const addMethod = (meth: Method) => {
    if (methods.some((x) => x.name === meth.name)) throw new GenError("name_collision", `client method ${meth.name} is derived twice`);
    methods.push(meth);
    if (meth.tool) tools.push([meth.name, meth.tool]);
  };
  for (const op of ops) {
    if (op.audience !== "agent") continue;
    const doc = opDoc(op, unlockedBy);
    const key = op.standard ? camel(op.id.replace(".", "_")) : (opKeys.get(op.id) as string);
    const opts = op.idempotency === "required" ? "options: KitIdempotent" : op.idempotency === "supported" ? "options?: KitCallOptions" : "";
    const pass = opts ? ", options" : "";
    if (op.standard) {
      // QA-SDK48-1: the bridge lists exactly one standard tool per app for agents, hold status (BRIDGE tools.ts); other
      // standard ops (tb.holds_pending) are app-to-app only and never a tool, so they get a client method but no definition
      if (op.id === "tb.hold_status") toolDefs.push({ name: mcpToolName(m.id, op.id), title: "Hold status", description: `Check a call to ${m.name} that is waiting for the owner's approval. Input: the holdId from the held result.`, inputSchema: standardOpInputSchema("tb.hold_status"), effect: "read" });
      addMethod({
        name: key,
        tool: mcpToolName(m.id, op.id),
        doc,
        signature: `(input: TbHoldStatusInput${opts ? `, ${opts}` : ""}): Promise<KitCall<TbHoldStatusOutput>>`,
        body: `(input${pass}) => call(mcp, TOOL.${key}, input${pass})`,
      });
    } else if (op.dynamic?.mode === "search") {
      const names = dynamicToolNames(m.id, op.id);
      toolDefs.push(
        { name: names.search, title: `${op.title}: search`, description: `Search the tools of "${op.title}". ${op.description}`, inputSchema: DYNAMIC_SEARCH_INPUT_SCHEMA, effect: "read" },
        { name: names.call, title: `${op.title}: call`, description: `Call one tool found with ${names.search}. ${op.description}`, inputSchema: DYNAMIC_CALL_INPUT_SCHEMA, effect: op.dynamic.effectCeiling },
      );
      addMethod({
        name: `${key}Search`,
        tool: names.search,
        doc: [...doc, `Search the dynamic tool catalog (ceilings: crud ${op.dynamic.crudCeiling.join(",")}, effect ${op.dynamic.effectCeiling}).`],
        signature: "(input: KitSearchInput): Promise<KitCall<KitCatalogEntry[]>>",
        body: `(input) => call(mcp, TOOL.${key}Search, input)`,
      });
      addMethod({
        name: `${key}Call`,
        tool: names.call,
        doc: [...doc, "Call one catalog tool by name; the bridge resolves its crud/effect before gating."],
        signature: "(input: KitDynamicCallInput, options?: KitCallOptions): Promise<KitCall<unknown>>",
        body: `(input, options) => call(mcp, TOOL.${key}Call, input, options)`,
      });
    } else if (op.dynamic?.mode === "list") {
      addMethod({
        name: `${key}Tool`,
        tool: null,
        doc: [...doc, `Call one catalog entry (MCP tool \`${m.id}${TOOL_NAME_RULE.separator}<entry>\`; ceilings: crud ${op.dynamic.crudCeiling.join(",")}, effect ${op.dynamic.effectCeiling}).`],
        signature: "(entry: string, args: Record<string, unknown>, options?: KitCallOptions): Promise<KitCall<unknown>>",
        body: "(entry, args, options) => call(mcp, toolName(entry), args, options)",
      });
    } else {
      const P = pascal(op.id);
      // QA-SDK48-5 (forward, spec ≥ 0.1.73 `listing: "lazy"`): a lazy op is not listed; the bridge's more_search/more_call reach it
      const listing = (op as { listing?: string }).listing;
      staticOps.push({ id: op.id, effect: op.effect });
      if (listing === "lazy") lazyOps.push({ id: op.id, effect: op.effect });
      else toolDefs.push({ name: mcpToolName(m.id, op.id), title: op.title, description: op.description, inputSchema: op.input ?? { type: "object" }, effect: op.effect, ...(listing === "workflow" ? { listing: "workflow" } : {}) });
      addMethod({
        name: key,
        tool: mcpToolName(m.id, op.id),
        doc,
        signature: `(input: ${P}Input${opts ? `, ${opts}` : ""}): Promise<KitCall<${P}Output>>`,
        body: `(input${pass}) => call(mcp, TOOL.${key}, input${pass})`,
      });
    }
  }

  toolDefs.push(...lazyPairDefs(m.id, m.name, lazyOps, staticOps));
  // QA-SDK48-2: the bridge lists a skills tool for every app (BRIDGE tools.ts `tb_skills`)
  toolDefs.push({ name: `${m.id}${TOOL_NAME_RULE.separator}${TOOL_NAME_RULE.skillsOp}`, title: "Skills", description: `How to use ${m.name}. Without skillId: the skill index. With skillId: that skill's text.`, inputSchema: { type: "object", additionalProperties: false, properties: { skillId: { type: "string", maxLength: 64 } } }, effect: "read" });
  const skills = (m.skills ?? []).map((s) => {
    let text: string;
    try {
      text = readFileSync(resolve(lm.manifestDir, s.file), "utf8");
    } catch {
      throw new GenError("skill_file_missing", `skill ${s.id}: cannot read ${s.file} (skill files are relative to the manifest directory ${lm.manifestDir})`);
    }
    return { id: s.id, title: s.title, file: s.file, ...(s.when ? { when: s.when } : {}), text };
  });

  const out: string[] = [HEADER, `// Product ${m.id} ${m.version}, manifest ${digest}.`, ""];
  out.push(`export const PRODUCT = ${JSON.stringify(m.id)};`);
  out.push(`export const VERSION = ${JSON.stringify(m.version)};`);
  out.push(`export const MANIFEST_DIGEST = ${JSON.stringify(digest)};`, "");
  out.push("/** Manifest operation ids (manifest order). Person ops are reachable only from the app UI, never as MCP tools. */");
  out.push(`export const OP = ${objectLiteral([...opKeys].map(([id, key]) => [key, id]))} as const;`);
  out.push("export type OpId = (typeof OP)[keyof typeof OP];", "");
  // Person-audience ops (app UI only; Connect REQUESTS "no person-op types in tb-gen", BSA-08/12): ids, idempotency facts
  // and an id → {input, output} map so the UI types `callOp` from the kit instead of hand-written wrappers.
  const personOps = m.operations.filter((o) => o.audience === "person");
  out.push("/** Person-audience operation ids (called from the app UI with the client `callOp`, never MCP tools). */");
  out.push(`export const PERSON_OPS = ${JSON.stringify(personOps.map((o) => o.id))} as const;`);
  out.push("export type PersonOpId = (typeof PERSON_OPS)[number];", "");
  out.push("/** Manifest idempotency per operation id (`required` ops need an Idempotency key; the client `callOp` adds one itself). */");
  out.push(`export const IDEMPOTENCY = ${objectLiteral(m.operations.map((o) => [o.id, o.idempotency]))} as const;`, "");
  const io = (o: (typeof m.operations)[number], part: "Input" | "Output") => ((part === "Input" ? o.input : o.output) ? `${pascal(o.id)}${part}` : part === "Input" ? "Record<string, never>" : "unknown");
  out.push("/** Input/output types of every person-audience operation, keyed by op id. */");
  out.push(`export interface PersonOps {${personOps.map((o) => `\n  ${JSON.stringify(o.id)}: { input: ${io(o, "Input")}; output: ${io(o, "Output")} };`).join("")}${personOps.length ? "\n" : ""}}`, "");
  out.push(`/** MCP tool names the bridge derives (\`<product>${TOOL_NAME_RULE.separator}<op>\`, search-mode \`_search\`/\`_call\`, hold status). */`);
  out.push(`export const TOOL = ${objectLiteral(tools)} as const;`);
  out.push("export type ToolName = (typeof TOOL)[keyof typeof TOOL];", "");
  out.push(`/** Tool name of a dynamic list-mode catalog entry: \`<product>${TOOL_NAME_RULE.separator}<entry>\`. */`);
  out.push(`export function toolName(entry: string): string {\n  return \`\${PRODUCT}${TOOL_NAME_RULE.separator}\${entry}\`;\n}`, "");
  out.push(...types.flatMap((t) => [t, ""]));
  out.push(...em.declarations.flatMap((t) => [t, ""]));
  out.push(RUNTIME, "");
  out.push("/**");
  out.push(" * Agent tool definitions: the names the bridge lists for a grant that allows every op, with title, description, the");
  out.push(" * input schema as the manifest derives it (the bridge may apply tighter limits) and effect. A harness registers these");
  out.push(" * and routes each call through the bridge (`createKitClient`");
  out.push(" * or its own MCP client): the grant, Rules, holds and receipts still decide every call. `listing: \"workflow\"`");
  out.push(" * tools are listed only when the agent's grant names them; dynamic list-mode entries are per agent and not here.");
  out.push(" */");
  out.push(`export const TOOLS: readonly KitToolDef[] = ${JSON.stringify(toolDefs, null, 2)};`, "");
  out.push("/** MCP annotations exactly as the bridge sets them (all three always present; MCP defaults would differ). */");
  out.push("export function toolAnnotations(effect: KitToolDef[\"effect\"]): { readOnlyHint: boolean; destructiveHint: boolean; openWorldHint: boolean } {");
  out.push("  return { readOnlyHint: effect === \"read\", destructiveHint: effect === \"destructive\", openWorldHint: effect === \"outward\" || effect === \"money\" };");
  out.push("}", "");
  out.push("/** Skill texts as shipped (raw, unrendered: `{{…}}` variables are filled by Core and the bridge). */");
  out.push(`export const SKILLS: readonly KitSkill[] = ${JSON.stringify(skills, null, 2)};`, "");
  out.push("/** One typed method per agent-audience operation (incl. dynamic search/call and hold status). */");
  out.push("export interface KitClient {");
  for (const meth of methods) out.push(`  /**\n${meth.doc.map((l) => `   * ${l}`).join("\n")}\n   */`, `  ${meth.name}${meth.signature};`);
  out.push("}", "");
  out.push("/** Typed client over the bridge MCP tools. `mcp` is any MCP client adapter; this kit holds no transport code. */");
  out.push("export function createKitClient(mcp: KitMcp): KitClient {");
  out.push("  return {");
  for (const meth of methods) out.push(`    ${meth.name}: ${meth.body},`);
  out.push("  };", "}", "");
  return out.join("\n");
}

function objectLiteral(entries: [string, string][]): string {
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}\n}`;
}

